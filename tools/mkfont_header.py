"""mkfont_header.py: src/font8x16.h (ASCII 32-126 of Spleen 8x16, 16 row bytes each) for the launcher UI.

usage: python3 tools/mkfont_header.py
Spleen is BSD 2-Clause (font/LICENSE-spleen), the same font the English game text uses.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import bigram  # noqa: E402

g = bigram.bdf_glyphs()
rows = [", ".join(f"0x{b:02x}" for b in g[chr(c)]) for c in range(32, 127)]
out = ["// generated by tools/mkfont_header.py from Spleen 8x16 (BSD 2-Clause, font/LICENSE-spleen)",
       "#pragma once", "#include <cstdint>", "static const uint8_t kFont8x16[95][16] = {"]
out += [f"    {{{r}}}," for r in rows] + ["};", ""]
(ROOT / "src/font8x16.h").write_text("\n".join(out), encoding="ascii")
print("wrote src/font8x16.h")
